import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, writeFile, rm, readFile } from "node:fs/promises";
import { createServer as httpServer } from "node:http";
import path from "node:path";
import os from "node:os";
import { chromium } from "playwright-core";
import { resolveBrowserPath } from "../resolveBrowserPath.js";
import { createServer } from "../../src/server/server.js";

const browserPath = resolveBrowserPath();
test("temporary share UI creates, pairs by link, downloads on mobile, and cancels", { skip: !browserPath, timeout: 60000 }, async (t) => {
  const dir = await mkdtemp(path.join(os.tmpdir(), "wiki-share-ui-"));
  const app = await createServer({ port: 0, dataDir: path.join(dir, "data") });
  let browser;
  t.after(async () => {
    await browser?.close(); await app.close();
    assert.equal(path.dirname(dir), path.resolve(os.tmpdir()));
    assert.ok(path.basename(dir).startsWith("wiki-share-ui-"));
    await rm(dir, { recursive: true, force: true, maxRetries: 3 });
  });
  const blocker = httpServer();
  await new Promise((resolve) => blocker.listen(0, "127.0.0.1", resolve));
  const port = blocker.address().port;
  await new Promise((resolve) => blocker.close(resolve));
  const api = (route, body, method = "POST") => fetch(new URL(route, app.url), { method, headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
  await api("/api/lan-sharing", { autoStart: false, port }, "PUT");
  await api("/api/lan-sharing", { enabled: true });
  browser = await chromium.launch({ executablePath: browserPath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  const errors = [];
  page.on("pageerror", (failure) => errors.push(failure.message));
  await page.addInitScript(() => Object.defineProperty(navigator, "clipboard", { value: { writeText: async (text) => { window.copiedText = text; } } }));
  await page.goto(app.url);
  await page.getByRole("link", { name: "临时分享", exact: true }).click();
  await page.getByRole("heading", { name: "临时分享", exact: true }).waitFor();
  const sourcePath = path.join(dir, "中文文件.txt");
  await writeFile(sourcePath, "shared from UI");
  await page.getByLabel("本机文件或目录路径").fill(sourcePath);
  await page.getByRole("button", { name: "创建临时分享", exact: true }).click();
  await page.getByRole("heading", { name: "中文文件.txt", exact: true }).waitFor();
  await page.getByRole("button", { name: "复制链接 / 二维码", exact: true }).click();
  await page.getByLabel("分享链接").waitFor();
  const shareUrl = new URL(await page.getByLabel("分享链接").inputValue());
  shareUrl.hostname = "127.0.0.1";
  const guest = await browser.newPage({ viewport: { width: 390, height: 844 } });
  guest.on("pageerror", (failure) => errors.push(failure.message));
  await guest.goto(shareUrl.href);
  await guest.getByRole("heading", { name: "中文文件.txt", exact: true }).waitFor();
  assert.equal(await guest.getByRole("button", { name: "创建临时分享", exact: true }).count(), 0);
  assert.equal(await guest.getByRole("button", { name: "取消分享", exact: true }).count(), 0);
  const [download] = await Promise.all([guest.waitForEvent("download"), guest.getByRole("link", { name: "下载", exact: true }).click()]);
  assert.equal(download.suggestedFilename(), "中文文件.txt");
  assert.equal(await readFile(await download.path(), "utf8"), "shared from UI");
  assert.ok(await guest.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1));
  // Keep a repeatable screenshot for visual inspection without touching application data.
  await page.screenshot({ path: path.join(dir, "desktop.png"), fullPage: true });
  await page.getByRole("button", { name: "取消分享", exact: true }).click();
  await page.getByRole("heading", { name: "暂无临时分享", exact: true }).waitFor();
  assert.deepEqual(errors, []);
});
