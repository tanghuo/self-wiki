async function connectHandles(page, source, target, port, outputPort = 'value') {
  const from = source.locator(`.react-flow__handle.source[data-handleid="${outputPort}"]`);
  const to = target.locator(`.react-flow__handle.target[data-handleid="${port}"]`);
  await from.waitFor(); await to.waitFor();
  await page.evaluate(() => new Promise(requestAnimationFrame));
  const a = await from.boundingBox(), b = await to.boundingBox();
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
  await page.mouse.down(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 }); await page.mouse.up();
}
async function clickEdge(page) {
  const point = await page.locator('.react-flow__edge-path').evaluate((path) => {
    const p = path.getPointAtLength(path.getTotalLength() / 2), screen = new DOMPoint(p.x, p.y).matrixTransform(path.getScreenCTM());
    return { x: screen.x, y: screen.y };
  });
  await page.mouse.click(point.x, point.y);
  await page.locator('.react-flow__edge.selected').waitFor();
}

