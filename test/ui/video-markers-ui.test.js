import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import { mkdtemp, readFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright-core";
import { resolveBrowserPath } from "../resolveBrowserPath.js";
import { createServer } from "../../src/server/server.js";

const browserPath = resolveBrowserPath();
const options = { timeout: 60000, skip: !browserPath && "Browser required" };
async function setup(t) {
  const dir = await mkdtemp(path.join(os.tmpdir(), "wiki-markers-ui-"));
  const app = await createServer({ port: 0, dataDir: dir });
  let browser;
  t.after(async () => {
    await browser?.close(); await app.close();
    assert.equal(path.dirname(dir), path.resolve(os.tmpdir())); assert.ok(path.basename(dir).startsWith("wiki-markers-ui-"));
    await rm(dir, { recursive: true, force: true, maxRetries: 3 });
  });
  browser = await chromium.launch({ executablePath: browserPath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } }); page.setDefaultTimeout(12000);
  const errors = []; page.on("pageerror", (error) => errors.push(error.message)); t.after(() => assert.deepEqual(errors, []));
  const api = async (route, body) => {
    const response = await fetch(new URL(`api/${route}`, app.url), { method: body ? "POST" : "GET", headers: { "content-type": "application/json" }, body: body ? JSON.stringify(body) : undefined });
    assert.ok(response.ok); return response.json();
  };
  const bytes = await readFile(new URL("../fixtures/sample.webm", import.meta.url));
  const video = await (await fetch(new URL("api/videos", app.url), { method: "POST", headers: { "x-file-name": encodeURIComponent("标注演示.webm") }, body: bytes })).json();
  const note = await api("elements", { body: "镜头参考资料", tags: [] });
  await page.goto(`${app.url}#wiki`);
  await page.getByRole("button", { name: "打开内容：标注演示.webm", exact: true }).click();
  const player = page.locator(".wiki-detail video");
  await page.waitForFunction(() => document.querySelector(".wiki-detail video")?.readyState >= 1);
  await player.evaluate((element) => { element.muted = true; element.pause(); element.currentTime = 0.3; });
  await page.waitForFunction(() => document.querySelector(".wiki-detail video")?.currentTime >= 0.29 && !document.querySelector(".wiki-detail video").seeking);
  return { app, page, player, video, note, api };
}

test("video marker UI captures time, tags and links, plays a range and jumps back from referenced content", options, async (t) => {
  const { page, player, video, note, api } = await setup(t);
  await page.getByRole("button", { name: "标记当前时间", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "添加视频标注", exact: true });
  assert.equal(await editor.getByLabel("标注开始时间", { exact: true }).inputValue(), "00:00.3");
  await editor.getByLabel("标注结束时间", { exact: true }).fill("1.2");
  await editor.getByLabel("标注说明", { exact: true }).fill("推进镜头的细节");
  await editor.getByLabel("片段标签", { exact: true }).fill("运镜");
  await editor.getByRole("button", { name: "选择关联内容", exact: true }).click();
  await editor.getByLabel("搜索片段关联内容", { exact: true }).fill("镜头参考");
  await editor.getByRole("button", { name: "关联片段到：镜头参考资料", exact: true }).click();
  await editor.getByRole("button", { name: "保存标注", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  const panel = page.getByRole("region", { name: "视频标注", exact: true });
  await panel.getByText("推进镜头的细节", { exact: true }).waitFor();
  const marker = (await api(`elements/${video.id}/markers`)).markers[0];
  assert.deepEqual(marker.tags, ["运镜"]); assert.deepEqual(marker.links.map((link) => link.id), [note.id]);
  assert.deepEqual((await api(`elements/${video.id}`)).tags, []);
  assert.ok(Math.abs(await player.evaluate((element) => element.currentTime) - 0.3) < 0.05, "saving must preserve playback position");
  await panel.getByRole("button", { name: "播放标注：00:00.3–00:01.2", exact: true }).click();
  await page.waitForFunction(() => { const video = document.querySelector(".wiki-detail video"); return video?.paused && Math.abs(video.currentTime - 1.2) < 0.03; });
  await panel.getByRole("button", { name: "镜头参考资料", exact: true }).click();
  const refs = page.getByRole("region", { name: "关联的视频片段", exact: true });
  await refs.getByRole("button", { name: "标注演示.webm · 00:00.3–00:01.2", exact: true }).click();
  await page.waitForFunction(() => { const video = document.querySelector(".wiki-detail video"); return video && video.currentTime >= 0.3 && video.currentTime <= 1.21; });
  await page.waitForFunction(() => document.querySelector(".wiki-detail video")?.paused && document.querySelector(".wiki-detail video").currentTime >= 1.19);
  await panel.getByRole("button", { name: "编辑标注", exact: true }).click();
  const edit = page.getByRole("dialog", { name: "编辑视频标注", exact: true });
  await edit.getByLabel("标注结束时间", { exact: true }).fill("");
  await edit.getByLabel("标注说明", { exact: true }).fill("时间点说明");
  await edit.getByRole("button", { name: "保存标注", exact: true }).click();
  await edit.waitFor({ state: "hidden" });
  await panel.getByRole("button", { name: "播放标注：00:00.3", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".wiki-detail video")?.currentTime > 1.3);
  await page.screenshot({ path: ".local/video-markers-ui.png", fullPage: true });
  await panel.getByRole("button", { name: "删除标注", exact: true }).click();
  const confirmation = page.getByRole("dialog", { name: "删除视频标注？", exact: true });
  await confirmation.getByRole("button", { name: "取消", exact: true }).click();
  assert.equal((await api(`elements/${video.id}/markers`)).pagination.total, 1);
  await panel.getByRole("button", { name: "删除标注", exact: true }).click();
  await confirmation.getByRole("button", { name: "确认删除标注", exact: true }).click();
  await confirmation.waitFor({ state: "hidden" });
  await panel.getByText("还没有时间标注。", { exact: false }).waitFor();
  assert.equal((await api(`elements/${note.id}/video-references`)).pagination.total, 0);
});

test("marker editor retains failed and invalid drafts on mobile and hidden playback stays paused on return", options, async (t) => {
  const { page, video, api } = await setup(t);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "标记当前时间", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "添加视频标注", exact: true });
  await editor.getByLabel("标注结束时间", { exact: true }).fill("0.1");
  await editor.getByLabel("标注说明", { exact: true }).fill("保留这份草稿");
  await editor.getByRole("button", { name: "保存标注", exact: true }).click();
  await editor.getByText("结束时间须晚于开始时间，且不超过 7 天", { exact: true }).waitFor();
  assert.equal((await api(`elements/${video.id}/markers`)).pagination.total, 0);
  await editor.getByLabel("标注结束时间", { exact: true }).fill("");
  const route = `**/api/elements/${video.id}/markers`;
  await page.route(route, (request) => request.request().method() === "POST" ? request.fulfill({ status: 503, contentType: "application/json", body: '{"error":"保存暂时失败"}' }) : request.continue());
  await editor.getByRole("button", { name: "保存标注", exact: true }).click();
  await editor.getByText("保存暂时失败", { exact: true }).waitFor();
  assert.equal(await editor.getByLabel("标注说明", { exact: true }).inputValue(), "保留这份草稿");
  await page.screenshot({ path: ".local/video-markers-mobile.png", fullPage: true });
  const bounds = await editor.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  assert.equal(await editor.evaluate((element) => element.scrollWidth <= element.clientWidth + 1), true);
  await editor.getByRole("button", { name: "关闭视频标注", exact: true }).click();
  await page.getByRole("dialog", { name: "放弃标注修改？", exact: true }).getByRole("button", { name: "继续编辑", exact: true }).click();
  assert.equal(await editor.getByLabel("标注说明", { exact: true }).inputValue(), "保留这份草稿");
  await page.unroute(route);
  await editor.getByRole("button", { name: "保存标注", exact: true }).click();
  await editor.waitFor({ state: "hidden" });
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole("button", { name: "播放标注：00:00.3", exact: true }).click();
  await page.getByRole("link", { name: "Agent 对话", exact: true }).click();
  await page.waitForFunction(() => [...document.querySelectorAll("video")].every((video) => video.paused));
  await page.evaluate(() => { window.location.hash = "wiki"; });
  await page.locator(".wiki-detail video").waitFor({ state: "visible" });
  await page.waitForTimeout(400);
  assert.equal(await page.locator(".wiki-detail video").evaluate((video) => video.paused), true, "restoring Activity must not replay the last marker");
  await page.getByRole("button", { name: "返回", exact: true }).click();
  await page.getByLabel("搜索内容", { exact: true }).fill("保留这份草稿");
  await page.getByRole("button", { name: "打开内容：标注演示.webm", exact: true }).waitFor();
});
