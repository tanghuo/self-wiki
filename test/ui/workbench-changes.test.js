import { stubWorkbenchModels } from '../helpers/workbenchModels.js';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm, stat } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createServer, chromium } from '../helpers/authenticatedServer.js';
import { resolveBrowserPath } from '../resolveBrowserPath.js';

const executablePath = resolveBrowserPath();
test('workbench shows live file lists, net summaries, line diffs and conflict-safe undo on desktop and mobile', { timeout: 30000, skip: !executablePath }, async t => {
  const root = await mkdtemp(path.join(os.tmpdir(), 'wiki-workbench-changes-ui-'));
  let app, browser, workspace;
  const finish = Promise.withResolvers();
  t.after(async () => { finish.resolve(); await browser?.close(); await app?.close(); assert.equal(path.dirname(root), path.resolve(os.tmpdir())); assert.ok(path.basename(root).startsWith('wiki-workbench-changes-ui-')); await rm(root, { recursive: true, force: true, maxRetries: 3 }); });
  app = await createServer({ port: 0, dataDir: root, agentWorkbenchEnabled: true, async openWorkbenchEngine(_settings, callbacks) {
    workspace = callbacks.cwd;
    return { sessionId: 'changes-ui', version: 'test', capabilities: { verified: true, approvalMode: callbacks.approvalMode }, cancel() { finish.resolve(); }, async close() {}, async prompt(_text, delivery) {
      delivery('attempted');
      for (const [name, content] of [['main.js', 'const result = 1;\n'], ['main.js', 'const result = 2;\n'], ['guide.md', '# Guide\n'], ['empty.txt', ''], ['style.css', 'body { color: inherit; }\n']]) await callbacks.onRequest('fs/write_text_file', { path: path.join(callbacks.cwd, name), content });
      await finish.promise;
      await callbacks.onEvent('message.delta', { text: '已完成四个文件的修改。' }); return {};
    } };
  } });
  browser = await chromium.launch({ executablePath, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  await stubWorkbenchModels(page);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(app.url + '#workbench');
  await page.getByLabel('审批模式').click();
  await page.getByRole('dialog', { name: '选择审批模式' }).getByRole('button', { name: '全部允许', exact: true }).click();
  await page.getByLabel('任务内容').fill('整理四个项目文件');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  const live = page.locator('.workbench-live-changes');
  await live.getByText('4 个文件已更改', { exact: false }).waitFor();
  await live.locator('summary').click();
  await live.getByRole('button', { name: /main.js/ }).click();
  const dialog = page.getByRole('dialog', { name: '本轮文件变更' });
  await dialog.waitFor();
  assert.equal(await dialog.locator('.workbench-diff-line.add').count(), 1);
  assert.match(await dialog.getByRole('region', { name: '文件差异' }).innerText(), /const result = 2/);
  await page.getByRole('button', { name: '关闭变更查看' }).click();
  finish.resolve();
  const card = page.getByRole('region', { name: '本轮文件变更' });
  await card.getByText('已编辑 4 个文件').waitFor();
  assert.equal(await card.locator('.workbench-change-files > button').count(), 3);
  assert.match(await card.locator('header .workbench-change-counts').innerText(), /\+3/);
  await card.getByRole('button', { name: '再显示 1 个文件' }).click();
  assert.equal(await card.locator('.workbench-change-files > button').count(), 4);
  await mkdir('.local/workbench-ui', { recursive: true });
  await page.screenshot({ path: '.local/workbench-ui/changes-summary-desktop.png' });
  await card.getByRole('button', { name: '查看变更' }).click();
  await dialog.waitFor();
  await page.screenshot({ path: '.local/workbench-ui/changes-diff-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const bounds = await dialog.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391);
  await page.screenshot({ path: '.local/workbench-ui/changes-diff-mobile.png' });
  await page.getByRole('button', { name: '关闭变更查看' }).click();
  await writeFile(path.join(workspace, 'main.js'), 'user edit\n');
  await card.getByRole('button', { name: '撤销 4 个文件' }).click();
  await page.getByRole('alert').filter({ hasText: '文件已被后续修改' }).waitFor();
  assert.equal(await readFile(path.join(workspace, 'guide.md'), 'utf8'), '# Guide\n');
  await writeFile(path.join(workspace, 'main.js'), 'const result = 2;\n');
  await card.getByRole('button', { name: '撤销 4 个文件' }).click();
  await card.getByRole('button', { name: '已撤销', exact: true }).waitFor();
  assert.equal(await stat(path.join(workspace, 'main.js')).catch(() => null), null);
  await page.reload();
  await page.getByRole('button', { name: '已撤销', exact: true }).waitFor();
  assert.deepEqual(errors, []);
});
