import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright-core";
import { resolveBrowserPath } from "../resolveBrowserPath.js";
import { selectedValue } from "../ui-select.js";
import { createServer } from "../../src/server/server.js";
import { defaultOrganizationConfig } from "../../src/shared/domain/organization.js";

const browserPath = resolveBrowserPath();
test("settings select Grok as chat engine and ordinary chat edits the preceding image without attachments", { timeout: 40000, skip: !browserPath && "Browser required" }, async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "wiki-grok-chat-ui-"));
  const previous = process.env.GROK_HOME; process.env.GROK_HOME = root;
  const config = defaultOrganizationConfig();
  config.executor.codexCli.executable = path.join(root, "missing-codex.exe");
  config.chat.grokBuild.executable = path.join(root, "grok.mjs");
  await writeFile(config.chat.grokBuild.executable, await readFile(new URL("../fixtures/grok-acp.txt", import.meta.url)));
  await writeFile(path.join(root, "organization.json"), JSON.stringify(config));
  const app = await createServer({ port: 0, dataDir: root });
  const browser = await chromium.launch({ executablePath: browserPath, headless: true });
  t.after(async () => {
    await browser.close(); await app.close(); if (previous === undefined) delete process.env.GROK_HOME; else process.env.GROK_HOME = previous;
    assert.equal(path.dirname(root), path.resolve(os.tmpdir())); assert.ok(path.basename(root).startsWith("wiki-grok-chat-ui-"));
    await rm(root, { recursive: true, force: true, maxRetries: 3 });
  });
  const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } }); page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(app.url); await page.getByRole("button", { name: "设置", exact: true }).click();
  await page.getByRole("button", { name: "Agent 连接", exact: false }).click();
  await page.getByLabel("聊天引擎", { exact: true }).selectOption("grok-build");
  assert.equal(await page.getByLabel("Grok 聊天程序路径").inputValue(), config.chat.grokBuild.executable);
  await page.getByRole("region", { name: "保存设置" }).getByRole("button", { name: "保存", exact: true }).click();
  await page.getByText("已保存", { exact: true }).waitFor();
  await page.goto(`${app.url}#agent?new=1`); await page.reload();
  await page.locator(".chat-connection > summary").filter({ hasText: "Grok Build 已连接" }).waitFor();
  await page.waitForFunction(() => document.querySelector('[aria-label="生图方式"]')?.getAttribute("data-value") === "grok-build");
  assert.equal(await page.getByLabel("原文直发生图", { exact: true }).isChecked(), false);
  await page.getByText("随当前 Grok 会话生图", { exact: true }).waitFor();
  const input = page.getByLabel("会话消息"), send = page.getByRole("button", { name: "发送消息", exact: true });
  await input.fill("GENERATE_CAT"); await send.click();
  await page.waitForFunction(() => document.querySelectorAll('.chat-process[data-state="completed"]').length === 1);
  await page.locator(".chat-generated-image").first().waitFor();
  const sessionId = Number(await selectedValue(page, "历史会话"));
  await page.reload(); await input.waitFor();
  await page.locator(".chat-connection > summary").filter({ hasText: "Grok Build 已连接" }).waitFor();
  await input.fill("EDIT_CAT"); await send.click();
  await page.waitForFunction(() => document.querySelectorAll('.chat-process[data-state="completed"]').length === 2);
  assert.equal(await page.locator(".chat-generated-image").count(), 2);
  const response = await fetch(new URL(`api/chat/sessions/${sessionId}`, app.url)), data = await response.json();
  assert.equal(data.turns.at(-1).inputAttachments.length, 0);
  assert.equal(data.turns.at(-1).directImage, false);
  await page.screenshot({ path: ".local/grok-chat-ui.png" });
  assert.deepEqual(errors, []);
});
