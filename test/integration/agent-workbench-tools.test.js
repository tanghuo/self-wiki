import { test } from 'node:test';
import assert from 'node:assert/strict';
import { initDb } from '../../src/server/data/sqlite.js';
import { createAgentWorkbenchRepository } from '../../src/server/data/agentWorkbenchRepository.js';
import { createAgentWikiRepository } from '../../src/server/data/agentWikiRepository.js';
import { createAgentTools } from '../../src/server/application/agentTools/service.js';
import { createElementRepository } from '../../src/server/data/elementRepository.js';

test('Wiki tools only propose; acceptance shares source version checks and rolls back on conflict; drafts detect concurrent edits', async t => {
  const db = initDb(':memory:'); t.after(() => db.close());
  const wiki = createElementRepository(db), repo = createAgentWikiRepository(db), workbench = createAgentWorkbenchRepository(db);
  const source = wiki.createText({ body: 'original', tags: [], creationSource: 'manual' });
  const workspace = workbench.createWorkspace({ kind: 'scratch', userPath: 'fixture', path: 'fixture', identity: 'fixture' });
  const session = workbench.createSession({ workspaceId: workspace.id, engine: 'fixture', policy: {} });
  const turn = workbench.startTurn(workbench.queueTurn(session.id, 'tool-test', { text: 'fixture' }).id);
  const tools = createAgentTools({ wiki, repo, tasks: {} });
  const call = tools.forTurn({ sessionId: session.id, turnId: turn.id, assertLive() {}, onResourceWait() {} });
  const input = { requestKey: 'proposal-1', proposal: { kind: 'add_tags', elementId: source.id, sourceIds: [], tags: ['proposed'], reason: 'synthetic evidence' } };
  await assert.rejects(call({ name: 'wiki_propose', input }), { code: 'READ_REQUIRED' });
  const read = await call({ name: 'wiki_read', input: { elementId: source.id } }); assert.ok(read.version);
  const suggestion = await call({ name: 'wiki_propose', input });
  assert.deepEqual(wiki.get(source.id).tags, []);
  wiki.update(source.id, { body: 'edited by user', tags: [] });
  assert.throws(() => tools.decideProposal(suggestion.id, session.id, { requestKey: 'accept-1', decision: 'accept' }), { statusCode: 409 });
  assert.deepEqual(wiki.get(source.id).tags, []); assert.equal(repo.list(session.id)[0].state, 'pending');
  await call({ name: 'wiki_read', input: { elementId: source.id } });
  const next = await call({ name: 'wiki_propose', input: { ...input, requestKey: 'proposal-2' } });
  tools.decideProposal(next.id, session.id, { requestKey: 'accept-2', decision: 'accept' });
  assert.deepEqual(wiki.get(source.id).tags, ['proposed']);
  const first = tools.saveDraft(session.id, { revision: 0, text: 'saved draft', attachments: [] });
  assert.equal(first.text, 'saved draft');
  assert.ok(first.requestKey);
  assert.equal(tools.saveDraft(session.id, { revision: 0, text: 'saved draft', attachments: [] }).requestKey, first.requestKey);
  assert.throws(() => tools.saveDraft(session.id, { revision: 0, text: 'stale window', attachments: [] }), { code: 'DRAFT_CONFLICT' });
  assert.equal(tools.draft(session.id).text, 'saved draft');
  workbench.finish(turn.id, 'completed');
  const queued = workbench.queueTurn(session.id, first.requestKey, { text: first.text, artifactIds: [] });
  assert.equal(tools.draft(session.id).text, '');
  assert.equal(workbench.queueTurn(session.id, first.requestKey, { text: first.text, artifactIds: [] }).id, queued.id);
  assert.throws(() => workbench.queueTurn(session.id, first.requestKey, { text: 'changed' }), { statusCode: 409 });
});
test('unchanged task polling forces a resource yield and tools cannot supply another session identity', async () => {
  let yielded = 0;
  const tools = createAgentTools({ repo: {}, wiki: {}, tasks: { get: () => ({ id: 1, state: 'queued', revision: 1 }) } });
  const call = tools.forTurn({ sessionId: 2, turnId: 3, assertLive() {}, onResourceWait: () => yielded++ });
  await assert.rejects(call({ name: 'task_status', input: { taskId: 1, sessionId: 999 } }), { code: 'INVALID_TOOL_INPUT' });
  assert.equal((await call({ name: 'task_status', input: { taskId: 1 } })).state, 'queued');
  await call({ name: 'task_status', input: { taskId: 1 } });
  assert.equal((await call({ name: 'task_status', input: { taskId: 1 } })).waitReason, 'resource_wait');
  assert.equal(yielded, 1);
});
