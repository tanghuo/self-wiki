test("text usage sorting combines copies and references before filtering and pagination", (t) => {
  const db = initDb(":memory:"); t.after(() => db.close());
  const repo = createElementRepository(db);
  const mixed = repo.createText({ body: "常用 混合", tags: ["常用"] });
  const copied = repo.createText({ body: "常用 复制", tags: ["常用"] });
  const unused = repo.createText({ body: "常用 未使用", tags: ["常用"] });
  const other = repo.createText({ body: "其他", tags: [] });
  db.prepare("UPDATE elements SET updated_at=?").run("2026-01-01T00:00:00.000Z");
  repo.recordUsage(mixed.id, "copy"); repo.recordUsage(mixed.id, "reference"); repo.recordUsage(mixed.id, "reference");
  repo.recordUsage(copied.id, "copy"); repo.recordUsage(copied.id, "copy");
  for (let i = 0; i < 4; i++) repo.recordUsage(other.id, "reference");
  const query = elementQuery(new URLSearchParams("kind=text&sort=usage&q=常用&tag=常用&pageSize=1"));
  assert.deepEqual(repo.list({ kind: "text" }).elements.map((e) => e.id), [other.id, unused.id, copied.id, mixed.id]);
  assert.equal(repo.list(query).pagination.total, 3);
  assert.deepEqual(repo.list({ ...query, throughPage: 3 }).elements.map((e) => e.id), [mixed.id, copied.id, unused.id]);
  assert.equal(repo.list({ ...query, page: 2 }).elements[0].id, copied.id);
  assert.deepEqual(repo.list({ ...query, throughPage: 3 }).elements.map((e) => e.copyCount), [1, 2, 0]);
  assert.equal(createElementRepository(db, { publicOnly: true }).list({ kind: "text" }).elements[0].copyCount, undefined);
  repo.recordUsage(copied.id, "reference");
  assert.equal(repo.list(query).elements[0].id, copied.id, "Ties use update time then ID");
  repo.trash(copied.id);
  assert.equal(repo.list(query).pagination.total, 2);
  assert.equal(repo.list(query).elements[0].id, mixed.id);
  assert.throws(() => elementQuery(new URLSearchParams("kind=text&sort=bogus")), /排序/);
  assert.throws(() => elementQuery(new URLSearchParams("kind=image&sort=usage")), /排序/);
  assert.throws(() => createElementRepository(db, { publicOnly: true }).list(query), /仅限本机/);
});

test("usage events retain time, rank within a half-open range, and follow element lifecycle", (t) => {
  const db = initDb(":memory:"); t.after(() => db.close());
  const repo = createElementRepository(db), service = createElementService(repo);
  const a = repo.createText({ body: "first", tags: [] }), b = repo.createText({ body: "second", tags: [] });
  assert.equal(service.usage(new URLSearchParams()).summary.total, 0);
  repo.recordUsage(a.id, "copy");
  assert.ok(db.prepare("SELECT occurred_at FROM element_usage_events").get().occurred_at >= Date.now() - 1000);
  assert.equal(repo.get(a.id).updatedAt, a.updatedAt, "Recording usage must not reorder the library");
  assert.equal(repo.get(a.id).copyCount, undefined, "Regular content responses do not carry metrics");
  db.prepare("UPDATE element_usage_events SET occurred_at=100").run();
  const insert = db.prepare("INSERT INTO element_usage_events(element_id,action,occurred_at) VALUES(?,?,?)");
  insert.run(a.id, 2, 200); insert.run(a.id, 2, 300);
  insert.run(b.id, 1, 200); insert.run(b.id, 1, 299);
  let stats = repo.usage({ from: 200, to: 300, sort: "total" });
  assert.deepEqual({ ...stats.summary }, { total: 3, copies: 2, references: 1, elements: 2 });
  assert.deepEqual(stats.elements.map((e) => e.id), [b.id, a.id]);
  assert.equal(stats.elements[0].lastUsedAt, 299);
  assert.deepEqual(repo.usage({ from: 200, to: 300, sort: "reference" }).elements.map((e) => e.id), [a.id]);
  migrateWiki(db);
  assert.equal(db.prepare("SELECT count(*) AS n FROM element_usage_events").get().n, 5);
  assert.throws(() => repo.recordUsage(a.id, "invalid"), /无效/);
  assert.throws(() => repo.recordUsage(99999, "copy"), /不存在/);
  assert.throws(() => service.usage(new URLSearchParams("from=300&to=200")), /无效/);
  assert.throws(() => service.usage(new URLSearchParams("from=NaN")), /无效/);
  assert.throws(() => service.usage(new URLSearchParams("sort=bogus")), /无效/);
  repo.trash(a.id);
  assert.throws(() => repo.recordUsage(a.id, "copy"), /回收站/);
  assert.ok(repo.usage({ from: 0, to: 400, sort: "total" }).elements.find((e) => e.id === a.id).deletedAt);
  repo.restore(a.id);
  assert.equal(repo.usage({ from: 0, to: 400, sort: "total" }).summary.total, 5);
  repo.trash(a.id); repo.purge(a.id);
  assert.equal(repo.usage({ from: 0, to: 400, sort: "total" }).summary.total, 2);
  assert.deepEqual(db.prepare("PRAGMA foreign_key_check").all(), []);
});

test("existing libraries migrate with zero history and migration failure rolls back", (t) => {
  const db = initDb(":memory:"); t.after(() => db.close());
  const repo = createElementRepository(db), note = repo.createText({ body: "existing", tags: [] });
  db.exec("DROP TABLE element_usage_events; DELETE FROM wiki_schema WHERE version=35");
  db.exec("CREATE TEMP TRIGGER fail_usage BEFORE INSERT ON wiki_schema WHEN NEW.version=35 BEGIN SELECT RAISE(ABORT,'fail usage'); END");
  assert.throws(() => migrateWiki(db), /fail usage/);
  assert.equal(db.prepare("SELECT name FROM sqlite_master WHERE name='element_usage_events'").get(), undefined);
  db.exec("DROP TRIGGER fail_usage");
  migrateWiki(db);
  assert.equal(repo.get(note.id).body, "existing");
  assert.equal(repo.usage({ from: 0, to: Date.now() + 1, sort: "total" }).summary.total, 0);
});
