import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
import { initDb } from '../../src/server/data/sqlite.js';
import { createAgentWorkbenchRepository } from '../../src/server/data/agentWorkbenchRepository.js';
import { createAgentTaskRepository } from '../../src/server/data/agentTaskRepository.js';
import { createAgentArtifactStore } from '../../src/server/assets/agentArtifactStore.js';

test('paid operation approval creates one task; restart never redispatches an attempted task; artifact references enforce ownership', async t => {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'wiki-agent-tasks-'));
  t.after(async () => { assert.equal(path.dirname(dir), path.resolve(os.tmpdir())); assert.ok(path.basename(dir).startsWith('wiki-agent-tasks-')); await rm(dir, { recursive: true, force: true, maxRetries: 3 }); });
  const db = initDb(':memory:'); t.after(() => db.close());
  const sessions = createAgentWorkbenchRepository(db), tasks = createAgentTaskRepository(db), store = createAgentArtifactStore(dir);
  const workspace = sessions.createWorkspace({ kind: 'scratch', userPath: dir, path: dir, identity: dir });
  const session = sessions.createSession({ workspaceId: workspace.id, engine: 'grok-build', policy: {} });
  const other = sessions.createSession({ workspaceId: workspace.id, engine: 'grok-build', policy: {} });
  const turn = sessions.startTurn(sessions.queueTurn(session.id, 'tasks-first', { text: 'image' }).id);
  const input = { sessionId: session.id, turnId: turn.id, kind: 'image.generate', input: { prompt: 'synthetic' }, executor: { id: 'grok-build' } };
  const op = tasks.submit(input);
  assert.equal(tasks.submit({ ...input, operationId: op.id }).id, op.id);
  assert.throws(() => tasks.submit({ ...input, operationId: op.id, input: { prompt: 'other' } }), { statusCode: 409 });
  assert.equal(tasks.list(session.id).length, 0);
  sessions.finish(turn.id, 'completed');
  const decision = { requestKey: 'approve-first', hash: op.hash, decision: 'allow' };
  const approved = tasks.decide(op.id, decision);
  assert.equal(tasks.decide(op.id, decision).taskId, approved.taskId);
  assert.equal(tasks.decide(op.id, { ...decision, requestKey: 'approve-again' }).taskId, approved.taskId);
  assert.equal(tasks.list(session.id).length, 1);
  const started = tasks.start(approved.taskId); tasks.dispatch(started.id, started.attemptId);
  tasks.recover(); assert.equal(tasks.task(started.id).state, 'unknown'); assert.equal(tasks.queued().length, 0);
  const bytes = await sharp({ create: { width: 8, height: 8, channels: 3, background: '#7d9960' } }).png().toBuffer();
  const artifact = await store.saveImage(bytes);
  const completed = tasks.finish(started.id, started.attemptId, 'succeeded', { reconciled: true }, [artifact]);
  const saved = tasks.artifact(completed.data.artifactIds[0], session.id);
  assert.deepEqual(await store.read(saved), bytes);
  assert.throws(() => tasks.artifact(saved.id, other.id), { statusCode: 404 });
  assert.deepEqual(await store.unreferenced(new Set()), [saved.storageKey]);
  assert.deepEqual(await store.unreferenced(new Set([saved.storageKey])), []);
  await writeFile(path.join(dir, 'agent-artifacts', 'objects', saved.storageKey), 'damaged');
  await assert.rejects(store.read(saved), { code: 'ARTIFACT_CORRUPT' });
  const events = sessions.events(session.id); assert.ok(events.every((event, i) => event.seq === i + 1));
});
test('cancelling the originating turn expires unpaid operations, while approved queued tasks cancel without dispatch', t => {
  const db = initDb(':memory:'); t.after(() => db.close());
  const sessions = createAgentWorkbenchRepository(db), tasks = createAgentTaskRepository(db);
  const workspace = sessions.createWorkspace({ kind: 'scratch', path: 'fixture', userPath: 'fixture', identity: 'fixture' });
  const s = sessions.createSession({ workspaceId: workspace.id, engine: 'fixture', policy: {} });
  const turn = sessions.startTurn(sessions.queueTurn(s.id, 'cancel-op', { text: 'fixture' }).id);
  const input = { sessionId: s.id, turnId: turn.id, kind: 'image.generate', input: { prompt: 'fixture' }, executor: { id: 'fixture' } };
  const pending = tasks.submit(input), op = tasks.submit(input);
  const approved = tasks.decide(op.id, { requestKey: 'approve-op', hash: op.hash, decision: 'allow' });
  tasks.expireTurn(turn.id);
  assert.equal(tasks.operation(pending.id).state, 'expired'); assert.equal(tasks.operation(op.id).state, 'approved');
  assert.throws(() => tasks.decide(pending.id, { requestKey: 'late-approve', hash: pending.hash, decision: 'allow' }), { statusCode: 409 });
  const task = tasks.task(approved.taskId);
  assert.equal(tasks.cancel(task.id, task.revision).state, 'cancelled'); assert.equal(tasks.queued().length, 0);
});
