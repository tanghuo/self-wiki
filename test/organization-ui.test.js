  assert.equal(await history.getByRole("button", { name: "批量修正", exact: true }).count(), 0);
  await history.getByRole("button", { name: "关闭整理历史", exact: true }).click();
  let unavailable;
  for (let index = 0; index < 12; index++) {
    let source;
    if (index === 11) {
      const response = await fetch(new URL("api/images", app.url), { method: "POST", headers: { "x-file-name": "history-preview.png" }, body: await readFile(new URL("../src/renderer/public/brand/self-wiki-64.png", import.meta.url)) });
      assert.equal(response.status, 201); source = await response.json();
    } else source = await api("elements", { body: `历史内容 ${index + 1}` });
    if (index === 10) unavailable = source.id;
    await api("organization/enqueue", { elementId: source.id });
    const { job } = await api("organization/claim", {});
    await api(`organization/jobs/${job.id}/context`, { leaseToken: job.leaseToken });
    await api(`organization/jobs/${job.id}/submit`, { leaseToken: job.leaseToken, requestKey: `history-${job.id}`, execution: { executor: "fixture" }, output: {
      summary: `第 ${index + 1} 份内容的整理摘要`, queries: [], tagAdds: [{ name: "资料", evidence: { kind: index === 11 ? "visual" : "text", elementId: source.id, quote: index === 11 ? "" : source.body, reason: "保留的整理依据" } }], relationAdds: [],
    } });
  }
  await page.route(`**/api/elements/${unavailable}`, (route) => route.fulfill({ status: 404, json: { error: "内容不可用" } }));
